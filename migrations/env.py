import os
from pathlib import Path
from logging.config import fileConfig

from sqlalchemy import engine_from_config
from sqlalchemy import pool

from alembic import context

# Import your Base from storage.py
from storage import Base

# this is the Alembic Config object
config = context.config

# Interpret the config file for Python logging.
if config.config_file_name is not None:
    fileConfig(config.config_file_name)

# --- Step 9.2: Configure Alembic to use the same DB path ---
def get_database_url() -> str:
    """Dynamically resolve the database URL to match the application's runtime path."""
    
    # 1. Check for explicit environment variable first
    db_path = os.getenv("HOTEL_CHATBOT_DB")
    
    # 2. Fallback to XDG standard path if env var is not set
    if not db_path:
        xdg_data_home = os.getenv("XDG_DATA_HOME", str(Path.home() / ".local" / "share"))
        app_data_dir = Path(xdg_data_home) / "hotel_chatbot"
        app_data_dir.mkdir(parents=True, exist_ok=True)
        db_path = str(app_data_dir / "hotel_chatbot.db")
        
    return f"sqlite:///{db_path}"

# Override Alembic's default sqlalchemy.url with our dynamic path
config.set_main_option("sqlalchemy.url", get_database_url())

# Set target_metadata to the Base's metadata so autogenerate works
target_metadata = Base.metadata

def run_migrations_offline() -> None:
    """Run migrations in 'offline' mode."""
    url = config.get_main_option("sqlalchemy.url")
    context.configure(
        url=url,
        target_metadata=target_metadata,
        literal_binds=True,
        dialect_opts={"paramstyle": "named"},
    )

    with context.begin_transaction():
        context.run_migrations()


def run_migrations_online() -> None:
    """Run migrations in 'online' mode."""
    connectable = engine_from_config(
        config.get_section(config.config_ini_section, {}),
        prefix="sqlalchemy.",
        poolclass=pool.NullPool,
    )

    with connectable.connect() as connection:
        context.configure(
            connection=connection, target_metadata=target_metadata
        )

        with context.begin_transaction():
            context.run_migrations()


if context.is_offline_mode():
    run_migrations_offline()
else:
    run_migrations_online()
    
